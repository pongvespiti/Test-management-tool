export const tagAnchor = (tag: string) => `tag-${tag.toLowerCase().replace(/[^a-z0-9]+/g, '-')}`;

function setHash(hash: string) {
  window.history.replaceState(
    window.history.state,
    '',
    `${window.location.pathname}${window.location.search}#${hash}`,
  );
}

function scrollToId(id: string) {
  document.getElementById(id)?.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

const currentHash = () =>
  typeof window === 'undefined' ? '' : decodeURIComponent(window.location.hash.slice(1));

const spinner = (
  <div className="flex justify-center py-10">
    <Spinner />
  </div>
);

/** Saves the document (e.g. for Postman or code generators). */
const download = () =>
  void downloadFile('/openapi.json', undefined, 'tmt-openapi.json').catch((err: unknown) =>
    notifyError(err, 'Download failed'),
  );

export function ApiDocsPage() {
  const openapi = useOpenApi();
  const parsed = useMemo(() => {
    if (!openapi.data) return null;
    try {
      return { doc: parseOpenApi(openapi.data), error: null };
    } catch (error) {
      return { doc: null, error };
    }
  }, [openapi.data]);

  const doc = parsed?.doc ?? null;
  return (
    <>
      <PageHeader
        title="REST API"
        subtitle={
          doc
            ? `${doc.title}${doc.version ? ` ${doc.version}` : ''} · ${pluralize(doc.operations.length, 'endpoint')} · generated by the server (OpenAPI 3.1)`
            : 'Endpoints, parameters and examples generated by the server'
        }
        actions={
          <>
            <Button variant="outline" onClick={download} disabled={!doc}>
              <Download />
              openapi.json
            </Button>
            <Button asChild variant="secondary" className="text-accent-foreground">
              <Link href={routes.apiTokens}>
                <Ticket />
                API tokens
              </Link>
            </Button>
          </>
        }
      />
      {openapi.isPending ? (
        spinner
      ) : openapi.isError || parsed?.error ? (
        <ErrorAlert
          error={openapi.error ?? parsed?.error}
          title="Could not load the API description"
          onRetry={() => void openapi.refetch()}
        />
      ) : doc ? (
        <Suspense fallback={spinner}>
          <ApiReference doc={doc} />
        </Suspense>
      ) : null}
    </>
  );
}

function ApiReference({ doc }: { doc: ApiDoc }) {
  const [origin] = useState(() => (typeof window === 'undefined' ? '' : window.location.origin));
  const [params, setParams] = useUrlSearchParams();
  const urlQuery = params.get('q') ?? '';
  const [query, setQueryText] = useState(urlQuery);
  const [syncedQuery, setSyncedQuery] = useState(urlQuery);
  // Follow back/forward navigation without fighting the text being typed.
  if (syncedQuery !== urlQuery) {
    setSyncedQuery(urlQuery);
    if (query !== urlQuery) setQueryText(urlQuery);
  }
  // Deep link `#op-<key>`: that operation starts open.
  const [opened, setOpened] = useState<string[]>(() => {
    const hash = currentHash();
    const key = hash.startsWith('op-') ? hash.slice(3) : '';
    return doc.operations.some((o) => o.key === key) ? [key] : [];
  });

  const setQuery = (q: string) => {
    setQueryText(q);
    setParams((prev) => {
      const next = new URLSearchParams(prev);
      if (q) next.set('q', q);
      else next.delete('q');
      return next;
    });
  };

  const index = useMemo(
    () => new Map(doc.operations.map((op) => [op.key, searchTextOf(op)])),
    [doc.operations],
  );
  const filtered = useMemo(() => {
    const terms = query.toLowerCase().split(/\s+/).filter(Boolean);
    if (terms.length === 0) return doc.operations;
    return doc.operations.filter((op) => {
      const text = index.get(op.key) ?? '';
      return terms.every((t) => text.includes(t));
    });
  }, [doc.operations, index, query]);
  const groups = useMemo(
    () =>
      doc.tags
        .map((tag) => ({ tag, ops: filtered.filter((op) => op.tag === tag.name) }))
        .filter((g) => g.ops.length > 0),
    [doc.tags, filtered],
  );

  // Scroll to the deep-linked operation or section once it is rendered.
  useEffect(() => {
    const hash = currentHash();
    if (!hash) return;
    const t = window.setTimeout(() => scrollToId(hash), 120);
    return () => window.clearTimeout(t);
  }, []);

  const onChange = (value: string[]) => {
    const added = value.find((k) => !opened.includes(k));
    if (added) setHash(`op-${added}`);
    setOpened(value);
  };

  return (
    <div className="flex flex-col gap-6">
      <ApiDocsIntro
        origin={origin}
        commonErrorCodes={doc.commonErrorCodes}
        sessionCookieName={doc.sessionCookieName}
      />
      <div className="flex flex-wrap items-center gap-4">
        <SearchInput
          aria-label="Search endpoints"
          placeholder="Search path, summary, error code…"
          value={query}
          onValueChange={setQuery}
          className="w-full sm:w-[420px]"
        />
        <span className="text-sm text-muted-foreground">
          {query
            ? `${filtered.length} of ${pluralize(doc.operations.length, 'endpoint')}`
            : pluralize(doc.operations.length, 'endpoint')}
        </span>
        {opened.length > 0 && (
          <Button variant="ghost" size="sm" className="text-primary" onClick={() => setOpened([])}>
            Collapse all
          </Button>
        )}
      </div>
      {groups.length === 0 ? (
        <Card>
          <EmptyState
            compact
            icon={<Search className="size-6" strokeWidth={1.6} />}
            title={`No endpoints match “${query}”`}
            description="Try a path segment (runs, junit), a summary word or an error code."
          />
        </Card>
      ) : (
        <div className="grid gap-6 lg:grid-cols-[minmax(0,1fr)_minmax(0,3fr)]">
          <nav aria-label="API sections" className="hidden lg:block">
            <Card className="sticky top-[76px] max-h-[calc(100vh-116px)] gap-0.5 overflow-y-auto p-2">
              {groups.map(({ tag, ops }) => (
                <a
                  key={tag.name}
                  href={`#${tagAnchor(tag.name)}`}
                  onClick={(e) => {
                    e.preventDefault();
                    setHash(tagAnchor(tag.name));
                    scrollToId(tagAnchor(tag.name));
                  }}
                  className="flex items-center justify-between gap-2 rounded-lg px-3 py-2 text-sm hover:bg-secondary"
                >
                  <span className="truncate">{tag.name}</span>
                  <Badge variant="secondary" className="px-1.5 py-0 text-[11px]">
                    {ops.length}
                  </Badge>
                </a>
              ))}
            </Card>
          </nav>
          <div className="flex min-w-0 flex-col gap-8">
            {groups.map(({ tag, ops }) => (
              <section
                key={tag.name}
                id={tagAnchor(tag.name)}
                aria-labelledby={`${tagAnchor(tag.name)}-title`}
                className="scroll-mt-[76px]"
              >
                <div className="mb-1 flex items-baseline gap-2">
                  <h2 id={`${tagAnchor(tag.name)}-title`} className="text-lg font-semibold">
                    {tag.name}
                  </h2>
                  <span className="text-sm text-muted-foreground">
                    {pluralize(ops.length, 'endpoint')}
                  </span>
                </div>
                {tag.description && (
                  <p className="mb-3 text-sm text-muted-foreground">{tag.description}</p>
                )}
                <Card className="gap-0 py-0">
                  <Accordion type="multiple" value={opened} onValueChange={onChange}>
                    {ops.map((op) => (
                      <OperationItem key={op.key} doc={doc} op={op} origin={origin} />
                    ))}
                  </Accordion>
                </Card>
              </section>
            ))}
          </div>
        </div>
      )}
    </div>
  );
}

function OperationItem({ doc, op, origin }: { doc: ApiDoc; op: ApiOperation; origin: string }) {
  return (
    <AccordionItem value={op.key} id={`op-${op.key}`} className="scroll-mt-[76px]">
      <AccordionTrigger
        aria-label={`${op.method.toUpperCase()} ${op.path} — ${op.summary}`}
        className="items-center rounded-none px-4 py-2.5 hover:no-underline"
      >
        <span className="flex min-w-0 flex-1 items-start gap-3">
          <span className="pt-px">
            <MethodBadge method={op.method} />
          </span>
          <span className="min-w-0 flex-1">
            <span
              className={`block font-mono text-sm font-semibold [overflow-wrap:anywhere] ${op.deprecated ? 'line-through' : ''}`}
            >
              {/* Prefer line breaks after "/" on narrow screens. */}
              {op.path.split('/').map((part, i) => (
                <Fragment key={i}>
                  {i > 0 && (
                    <>
                      /<wbr />
                    </>
                  )}
                  {part}
                </Fragment>
              ))}
            </span>
            <span className="block text-sm font-normal text-muted-foreground">{op.summary}</span>
          </span>
          <span className="hidden pt-px sm:inline-flex">
            <MinRoleLabel role={op.minRole} />
          </span>
        </span>
      </AccordionTrigger>
      <AccordionContent className="px-4 pt-1 pb-4">
        <ApiOperationDetails doc={doc} op={op} origin={origin} />
      </AccordionContent>
    </AccordionItem>
  );
}
